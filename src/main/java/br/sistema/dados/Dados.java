package br.sistema.dados;

public class Dados {
	private double energia;   
	private double emissoes;  
	private double residuos;  

	public Dados() {}

	public double getEnergia() { return energia; }
	public void setEnergia(double energia) { this.energia = energia; }

	public double getEmissoes() { return emissoes; }
	public void setEmissoes(double emissoes) { this.emissoes = emissoes; }

	public double getResiduos() { return residuos; }
	public void setResiduos(double residuos) { this.residuos = residuos; }
}
